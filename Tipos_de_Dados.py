# Tipos de dados no python - revisão

#INT
idade = 17
print("idade : ")
print(idade)
print(type(idade), "\n")

#FLOAT (Ponto Flutuante) valores com virgula
altura = 1.60
print("altura : ")
print(altura)
print(type(altura), "\n")

#STR (string) texto
nome = "Jonas Carvalho"
print("nome : ")
print(nome)
print(type(nome), "\n")

#BOOL boleano: SIM, NÃO, VERDADE, MENTIRA, LIGADO, DESIGADO
briga = False
print("briga : ")
print(briga)
print(type(briga), "\n")

#List Lista (Coleção Ordenada)
frutas = ["bluberry", "morango", "manga"]
print("frutas : ")
print(frutas)
print(type(frutas), "\n")

#Tuple Tuplas Duplas, como por exemplo, coordenadas
coordenadas = (52.640, 24.325)
print("coordenadas : ")
print(coordenadas)
print(type(coordenadas), "\n")

#Set - Conjunto
numeros = {1, 2, 3, 3, 4, 5, 5, 5}
print("numeros : ")
print(numeros)
print(type(numeros), "\n")

#Dict - Dicionario
pessoas = {"nome" : "NathIngrid", "idade" : 17}
print("pessoas : ")
print(pessoas)
print(type(pessoas), "\n")

#None Type - quanod não tem nada, mas é preciso informar um valor
valor = None
print("valor : ")
print(valor)
print(type(valor), "\n")

